-- 01-schema.sql
-- 프레임워크별 데모 DB({fw}_customer_db)와 테스트 DB({fw}_customer_test_db)를 생성한다.
-- customers DDL은 'SQL Injection/Spring.md'의 MySQL 예제 환경과 동일하다.
-- 모든 구문은 IF NOT EXISTS를 사용하므로 기존 Volume에 다시 적용해도 안전하다(provision).

-- spring_boot
CREATE DATABASE IF NOT EXISTS spring_boot_customer_db DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS spring_boot_customer_db.customers (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    last_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE = InnoDB DEFAULT CHARACTER SET = utf8mb4;

CREATE DATABASE IF NOT EXISTS spring_boot_customer_test_db DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS spring_boot_customer_test_db.customers (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    last_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE = InnoDB DEFAULT CHARACTER SET = utf8mb4;

